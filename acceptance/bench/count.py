def files(root: Path) -> list[str]:
    out = subprocess.run(
        ["git", "-C", str(root), "ls-files"], check=True, capture_output=True, text=True
    ).stdout
    return [f for f in out.splitlines() if Path(f).suffix in CODE and "node_modules" not in f]


def kind(root: Path, path: str) -> str:
    if TEST.search(path):
        return "test"
    try:
        head = (root / path).read_bytes()[:600]
    except OSError:
        return "missing"
    if (
        GENERATED.search(head)
        or path.endswith((".pb.go", ".gen.go", ".sql.go"))
        or "/gen/" in path
        or "routeTree.gen" in path
        or "/generated/" in path
        or "_generated" in path
    ):
        return "generated"
    return "production"


def cloc(root: Path, paths: list[str]) -> dict[str, int]:
    with tempfile.NamedTemporaryFile("w", suffix=".txt") as listing:
        listing.write("\n".join(str(root / p) for p in paths))
        listing.flush()
        out = subprocess.run(
            ["cloc", "--by-file", "--json", "--quiet", f"--list-file={listing.name}"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    data = json.loads(out)
    return {
        k[len(str(root)) + 1 :]: v["code"] for k, v in data.items() if k not in ("header", "SUM")
    }


def tally(root: Path, mapping: list[tuple[str, str]]) -> dict:
    by_kind: dict[str, list[str]] = defaultdict(list)
    for f in files(root):
        by_kind[kind(root, f)].append(f)
    totals: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for k, paths in by_kind.items():
        if k == "missing":
            continue
        for path, lines in cloc(root, paths).items():
            capability = next(
                (c for prefix, c in mapping if path.startswith(prefix)),
                "other:" + path.split("/")[0],
            )
            totals[capability][k] += lines
    return {c: dict(v) for c, v in totals.items()}


def main() -> None:
    ref, new = tally(Path(sys.argv[1]).resolve(), REF), tally(Path(sys.argv[2]).resolve(), NEW)
    caps = sorted(set(ref) | set(new))
    print(
        f"{'capability':32} {'ref prod':>9} {'new prod':>9} {'ref gen':>8} {'new gen':>8} {'ref test':>9} {'new test':>9}"
    )
    sums = defaultdict(int)
    for c in caps:
        r, n = ref.get(c, {}), new.get(c, {})
        row = [
            r.get("production", 0),
            n.get("production", 0),
            r.get("generated", 0),
            n.get("generated", 0),
            r.get("test", 0),
            n.get("test", 0),
        ]
        print(f"{c:32} " + " ".join(f"{v:>9}" for v in row))
        if c not in BACKEND_EXCLUDE and not c.startswith("other"):
            for i, v in enumerate(row):
                sums[i] += v
    print(f"{'BACKEND TOTAL':32} " + " ".join(f"{sums[i]:>9}" for i in range(6)))


if __name__ == "__main__":
    main()
